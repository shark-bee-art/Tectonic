        case .zoomIn:
            ["M 3.0 11.0 C 3.0 6.5816 6.5816 3.0 11.0 3.0 C 15.4184 3.0 19.0 6.5816 19.0 11.0 C 19.0 15.4184 15.4184 19.0 11.0 19.0 C 6.5816 19.0 3.0 15.4184 3.0 11.0 Z"]
        case .zoomOut:
